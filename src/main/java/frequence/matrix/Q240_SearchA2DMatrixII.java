package frequence.matrix;

/**
 * 240. 搜索二维矩阵 II
 *
 * <p>给定一个每行从左到右递增、每列从上到下递增的矩阵，判断目标值是否存在。
 *
 * <p>当前实现来自LeetCode已保存代码。从右上角开始，该位置同时具有“当前行最大”和
 * “当前列最小”的单调信息。这里的“双向单调”不是说从当前点沿两个方向都递增，而是说
 * 当前值同时为两个方向提供了相反的大小边界：在尚未排除的区域中，左边的值都不大于它，
 * 下边的值都不小于它。用更直观的话说，当前值正好夹在“左边的一批较小值”和
 * “下边的一批较大值”中间。
 *
 * <p>因此，当前值大于目标时，当前列从该位置向下的值只会更大，可以排除当前列；当前值
 * 小于目标时，当前行从该位置向左的值只会更小，可以排除当前行。一次比较必然排除一整行
 * 或一整列。
 *
 * <p>时间复杂度{@code O(M + N)}，额外空间复杂度{@code O(1)}。
 */
public class Q240_SearchA2DMatrixII {

    /**
     * 2026-08-30 我的右上角排除法。
     *
     * <p><b>结论：</b>这版正确，核心表述也很到位：右上角同时具备“左侧都更小、下方都更大”
     * 的双向单调信息，所以一次比较可以整行或整列排除。
     *
     * <p><b>严格表述：</b>它的核心并不是“双向都递增”，而是：当前值同时是剩余行的上界
     * 和剩余列的下界，因此比较一次就能排除一整行或一整列。这里的“剩余行、剩余列”特指
     * 当前尚未被排除的搜索区域。
     *
     * <p><b>通用解题视角（重要）：</b>很多查找题的关键trick，就是寻找一个同时控制两批
     * 候选值的“边界点”。如果当前值能够分别作为两批数据的上界和下界，那么将它与target
     * 比较一次，就可以证明其中一整批数据不可能包含答案，从而批量缩小搜索空间。本题的
     * 右上角只是这个通用思想在行列有序矩阵中的具体落点；真正需要记住的是“寻找能够产生
     * 确定性排除的边界”，而不是孤立地背诵起点位置。
     *
     * <p><b>面试记忆口诀：</b>右上角的值正好处于中间，左边都小，下边都大；大了往左，
     * 小了往下。
     *
     * <p><b>“双向单调”到底是什么意思：</b>它不是说两个方向的变化趋势相同，而是说右上角
     * 当前值{@code cur}在两个候选方向上分别构成上界和下界。在当前尚未排除的搜索区域中：
     * <pre>{@code
     * 同一行的左侧：matrix[row][j] <= cur
     * 同一列的下方：matrix[i][column] >= cur
     * }</pre>
     * 所以，{@code cur}正好夹在两批数中间：左边是一批不大于它的数，下边是一批不小于
     * 它的数。正是这两个相反方向的大小关系，使一次比较能够确定排除哪一批候选值。
     *
     * <p><b>复杂度修正：</b>
     * <ul>
     *     <li>原表述：时间复杂度{@code O(N)}。</li>
     *     <li>问题：矩阵同时有M行和N列，只写N无法准确说明指针的移动范围。</li>
     *     <li>正确结论：时间复杂度是{@code O(M + N)}，指针最多向下移动M次、向左移动N次；
     *     它并没有遍历矩阵中的全部{@code M * N}个元素，因此不是{@code O(MN)}。</li>
     * </ul>
     * 额外空间复杂度为{@code O(1)}。
     *
     * <p><b>核心点：</b>
     * <ol>
     *     <li>起点总是处在“大于一批数据a，同时小于另一批数据b”的位置上。</li>
     *     <li>将起点与target比较后，可以确定舍弃哪一整批数据，同时也唯一决定行走方向。</li>
     * </ol>
     *
     * <p>依据这个核心条件，起始点只能选择右上角或者左下角：
     * <pre>{@code
     * 右上角：左侧更小，下方更大；大了向左，小了向下。
     * 左下角：上方更小，右侧更大；大了向上，小了向右。
     * }</pre>
     * 左上角的右侧和下方都更大，右下角的左侧和上方都更小，一次比较无法判断应该排除
     * 哪个方向，因此不能作为这种排除法的起点。
     *
     * <p><b>循环不变量：</b>在当前尚未排除的搜索区域中，位置{@code (row, column)}是
     * 当前剩余行的最大值、当前剩余列的最小值。这里强调“剩余区域”，因为指针移动后，
     * 已经排除的行列不再参与判断：
     * <ul>
     *     <li>{@code cur < target}：当前行左侧满足{@code value <= cur < target}，整行都不可能
     *     命中，执行{@code row++}。</li>
     *     <li>{@code cur > target}：当前列下方满足{@code value >= cur > target}，整列都不可能
     *     命中，执行{@code column--}。</li>
     * </ul>
     */
    public static class Solution20260830 {

        public boolean searchMatrix(int[][] matrix, int target) {
            // 本题选择右上角作为起点：当前值夹在左侧较小值和下方较大值之间。
            // 当前值大了，排除当前列并向左；当前值小了，排除当前行并向下。
            int m = matrix.length;
            int n = matrix[0].length;
            int[] p = {0, n - 1};

            // 因为只会向下或向左，所以行不能越过m，列不能小于0。
            while (p[0] < m && p[1] >= 0) {
                if (matrix[p[0]][p[1]] == target) {
                    return true;
                } else if (matrix[p[0]][p[1]] < target) {
                    // 当前行中尚未排除的其他值都更小，可以舍弃当前整行。
                    p[0]++;
                } else {
                    // 当前列中尚未排除的其他值都更大，可以舍弃当前整列。
                    p[1]--;
                }
            }
            return false;
        }
    }

    public static class Solution {

        public boolean searchMatrix(int[][] matrix, int target) {
            int rows = matrix.length;
            int columns = matrix[0].length;
            int row = 0;
            int column = columns - 1;
            while (row < rows && column >= 0) {
                if (matrix[row][column] > target) {
                    column--;
                } else if (matrix[row][column] < target) {
                    row++;
                } else {
                    return true;
                }
            }
            return false;
        }
    }
}
