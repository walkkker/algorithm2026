public class PalindromeSubsequence {

    public int longestPalindromeSubseq(String s) {
        char[] chs = s.toCharArray();
        int n = chs.length;
        int[][] dp = new int[n][n];
        dp[0][0] = 1;
        dp[n - 1][n - 1] = 1;
        for (int L = n - 2; L >= 0; L--) {
            for (int R = 1; R < n; R++) {
                if (L > R) {
                    dp[L][R] = 0;
                } else if (L == R) {
                    dp[L][R] = 1;
                } else {
                    // TODO: (一开始没有第二个else-if)【错误】L==R 和 R > L 是不能统一讨论的！！！ 虽然依赖dp[L + 1][R - 1]是相同的。 但是 匹配的字符数量是不一样的！！！
                    // TODO： 【错误-重要】重要提醒：
                    //  （1）能确定的base case一定要先填好，能避免很多 写代码没有设计好的问题
                    //   (2) dp[i][j]填值时，还是要 考虑到i,j对应的语义。 伴随语义理解，就不会在L==R时，还+2了
                    if (chs[L] == chs[R]) {
                        dp[L][R] = 2 + dp[L + 1][R - 1];   // 特别注意，只有R>L时，才有这个情况
                    } else {
                        dp[L][R] = Math.max(dp[L + 1][R], dp[L][R - 1]);
                    }
                }
            }
        }
        // 本题的初始状态就是 L，R分别处在两侧作为起始点
        return dp[0][n - 1];
    }

    public static int dpTest(String s) {
        char[] chs = s.toCharArray();
        int len = chs.length;
        // TODO: 【注意】在char[]上跑范围模型，dp不应该是 dp[len+1]，因为chs[len]属于越界状态了。  l,r的区间应该保证在chs范围内
        int[][] dp = new int[len][len];
        // Step1: initialization
        for (int i = 0, j = 0; i < len; i++, j++) {
            dp[i][j] = 1;
        }
        // Step2: fill the grid
        for (int i = len - 2; i >= 0; i--) {
            for (int j = i + 1; j < len; j++) {
                int ans = 0;
                if (chs[i] == chs[j]) {
                    ans = 2 + dp[i + 1][j - 1];
                } else {
                    ans = Math.max(dp[i + 1][j], dp[i][j - 1]);
                }
                // TODO: 千万不要忘了 ans 填回 dp[i][j]
                dp[i][j] = ans;
            }
        }
        return dp[0][len - 1];
    }


}
